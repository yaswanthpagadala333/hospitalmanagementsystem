"""
pdf_generator.py
================
Professional PDF document generation using ReportLab's Platypus layout
engine (flowables + tables), rather than raw canvas drawing, so
documents automatically paginate and stay maintainable.

Produces:
  * Invoices (from a Bill)
  * Patient medical summaries (demographics + appointment history)
  * Prescriptions (single appointment's prescribed medicines)
  * Analytics summary reports (used by the analytics/reports view)
"""

from __future__ import annotations

from pathlib import Path
from typing import Optional

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer, HRFlowable,
)

from config import config
from models.billing import Bill
from models.patient import Patient
from models.appointment import Appointment
from utils.helpers import format_currency, now_iso
from utils.logger import get_logger

logger = get_logger(__name__)

_PRIMARY_COLOR = colors.HexColor("#1F4E79")
_ACCENT_COLOR = colors.HexColor("#2E86C1")
_LIGHT_GREY = colors.HexColor("#F2F2F2")

_styles = getSampleStyleSheet()
_styles.add(ParagraphStyle(name="HospitalTitle", parent=_styles["Title"], textColor=_PRIMARY_COLOR, fontSize=20))
_styles.add(ParagraphStyle(name="SectionHeading", parent=_styles["Heading2"], textColor=_PRIMARY_COLOR, spaceBefore=12, spaceAfter=6))
_styles.add(ParagraphStyle(name="RightAlign", parent=_styles["Normal"], alignment=TA_RIGHT))
_styles.add(ParagraphStyle(name="CenterSmall", parent=_styles["Normal"], alignment=TA_CENTER, fontSize=8, textColor=colors.grey))


def _letterhead(title: str) -> list:
    return [
        Paragraph(config.settings.hospital_name, _styles["HospitalTitle"]),
        Paragraph(title, _styles["Heading3"]),
        HRFlowable(width="100%", thickness=1.2, color=_ACCENT_COLOR, spaceAfter=10),
    ]


def _footer(elements: list) -> None:
    elements.append(Spacer(1, 16))
    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.grey, spaceAfter=6))
    elements.append(Paragraph(
        f"Generated by {config.APP_NAME} v{config.APP_VERSION} on {now_iso()}. "
        f"This document is computer-generated.",
        _styles["CenterSmall"],
    ))


# --------------------------------------------------------------------
# Invoice
# --------------------------------------------------------------------
def generate_invoice_pdf(bill: Bill, patient: Patient, output_path: Optional[Path] = None) -> Path:
    output_path = output_path or (config.REPORTS_DIR / f"invoice_{bill.bill_number}.pdf")
    doc = SimpleDocTemplate(str(output_path), pagesize=A4,
                             topMargin=20 * mm, bottomMargin=18 * mm, leftMargin=18 * mm, rightMargin=18 * mm)
    elements: list = _letterhead("Invoice")

    info_table = Table(
        [
            ["Invoice No.:", bill.bill_number, "Date:", bill.bill_date or now_iso()],
            ["Patient:", patient.full_name, "Patient Code:", patient.patient_code],
            ["Phone:", patient.phone, "Payment Status:", bill.payment_status],
        ],
        colWidths=[28 * mm, 62 * mm, 30 * mm, 50 * mm],
    )
    info_table.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    elements.append(info_table)
    elements.append(Spacer(1, 14))

    elements.append(Paragraph("Itemized Charges", _styles["SectionHeading"]))
    item_rows = [["#", "Description", "Type", "Qty", "Unit Price", "Amount"]]
    for idx, item in enumerate(bill.items, start=1):
        item_rows.append([
            str(idx), item.description, item.item_type, str(item.quantity),
            format_currency(item.unit_price), format_currency(item.amount),
        ])
    items_table = Table(item_rows, colWidths=[10 * mm, 62 * mm, 28 * mm, 14 * mm, 28 * mm, 28 * mm])
    items_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), _PRIMARY_COLOR),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("ALIGN", (3, 0), (-1, -1), "RIGHT"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, _LIGHT_GREY]),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    elements.append(items_table)
    elements.append(Spacer(1, 10))

    totals_rows = [
        ["Subtotal", format_currency(bill.subtotal)],
        [f"Tax ({bill.tax_percent:g}%)", format_currency(bill.tax_amount)],
        ["Discount", f"- {format_currency(bill.discount_amount)}"],
        ["Total Due", format_currency(bill.total_amount)],
    ]
    totals_table = Table(totals_rows, colWidths=[140 * mm, 30 * mm], hAlign="RIGHT")
    totals_table.setStyle(TableStyle([
        ("ALIGN", (1, 0), (1, -1), "RIGHT"),
        ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 10.5),
        ("LINEABOVE", (0, -1), (-1, -1), 1, _PRIMARY_COLOR),
        ("TOPPADDING", (0, -1), (-1, -1), 6),
    ]))
    elements.append(totals_table)

    if bill.payment_method:
        elements.append(Spacer(1, 8))
        elements.append(Paragraph(f"Payment Method: {bill.payment_method}", _styles["Normal"]))

    _footer(elements)
    doc.build(elements)
    logger.info("Generated invoice PDF: %s", output_path)
    return output_path


# --------------------------------------------------------------------
# Patient medical summary
# --------------------------------------------------------------------
def generate_patient_summary_pdf(patient: Patient, appointments: list[Appointment],
                                  output_path: Optional[Path] = None) -> Path:
    output_path = output_path or (config.REPORTS_DIR / f"patient_summary_{patient.patient_code}.pdf")
    doc = SimpleDocTemplate(str(output_path), pagesize=A4,
                             topMargin=20 * mm, bottomMargin=18 * mm, leftMargin=18 * mm, rightMargin=18 * mm)
    elements: list = _letterhead("Patient Medical Summary")

    demo_rows = [
        ["Patient Code:", patient.patient_code, "Age / Gender:", f"{patient.age} / {patient.gender}"],
        ["Phone:", patient.phone, "Blood Group:", patient.blood_group or "—"],
        ["Email:", patient.email or "—", "Allergies:", patient.allergies or "None recorded"],
        ["Address:", patient.address or "—", "Emergency Contact:",
         f"{patient.emergency_contact_name or '—'} ({patient.emergency_contact_phone or '—'})"],
    ]
    demo_table = Table(demo_rows, colWidths=[28 * mm, 62 * mm, 34 * mm, 46 * mm])
    demo_table.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    elements.append(demo_table)
    elements.append(Spacer(1, 14))

    elements.append(Paragraph("Appointment History", _styles["SectionHeading"]))
    if appointments:
        rows = [["Date", "Time", "Doctor", "Status", "Diagnosis"]]
        for a in appointments:
            rows.append([a.appointment_date, a.appointment_time, a.doctor_name or "—", a.status, a.diagnosis or "—"])
        table = Table(rows, colWidths=[24 * mm, 18 * mm, 42 * mm, 24 * mm, 62 * mm])
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), _PRIMARY_COLOR),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, _LIGHT_GREY]),
            ("FONTSIZE", (0, 0), (-1, -1), 8.5),
        ]))
        elements.append(table)
    else:
        elements.append(Paragraph("No appointment history on record.", _styles["Normal"]))

    _footer(elements)
    doc.build(elements)
    logger.info("Generated patient summary PDF: %s", output_path)
    return output_path


# --------------------------------------------------------------------
# Prescription
# --------------------------------------------------------------------
def generate_prescription_pdf(patient: Patient, doctor_name: str, appointment: Appointment,
                               prescriptions: list[dict], output_path: Optional[Path] = None) -> Path:
    output_path = output_path or (config.REPORTS_DIR / f"prescription_appt{appointment.id}.pdf")
    doc = SimpleDocTemplate(str(output_path), pagesize=A4,
                             topMargin=20 * mm, bottomMargin=18 * mm, leftMargin=18 * mm, rightMargin=18 * mm)
    elements: list = _letterhead("Prescription")

    header = Table(
        [
            ["Patient:", patient.full_name, "Date:", appointment.appointment_date],
            ["Age / Gender:", f"{patient.age} / {patient.gender}", "Prescribing Doctor:", doctor_name],
        ],
        colWidths=[28 * mm, 62 * mm, 34 * mm, 46 * mm],
    )
    header.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    elements.append(header)
    elements.append(Spacer(1, 8))
    if appointment.diagnosis:
        elements.append(Paragraph(f"<b>Diagnosis:</b> {appointment.diagnosis}", _styles["Normal"]))
        elements.append(Spacer(1, 10))

    elements.append(Paragraph("Rx", ParagraphStyle(name="Rx", fontSize=18, textColor=_PRIMARY_COLOR, fontName="Helvetica-BoldOblique")))
    rows = [["Medicine", "Dosage", "Frequency", "Duration", "Qty"]]
    for p in prescriptions:
        rows.append([p["medicine_name"], p["dosage"], p["frequency"], f"{p['duration_days']} days", str(p["quantity"])])
    table = Table(rows, colWidths=[48 * mm, 28 * mm, 32 * mm, 26 * mm, 16 * mm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), _PRIMARY_COLOR),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, _LIGHT_GREY]),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
    ]))
    elements.append(table)

    elements.append(Spacer(1, 30))
    elements.append(Paragraph("_________________________", _styles["Normal"]))
    elements.append(Paragraph(f"{doctor_name} — Signature", _styles["Normal"]))

    _footer(elements)
    doc.build(elements)
    logger.info("Generated prescription PDF: %s", output_path)
    return output_path
